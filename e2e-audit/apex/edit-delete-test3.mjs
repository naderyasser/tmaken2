import { chromium } from '@playwright/test'
const BASE = 'https://tamkeen-v2.base.meena.sa'
const browser = await chromium.launch()
const page = await (await browser.newContext({ viewport: { width: 1512, height: 900 }, locale: 'ar' })).newPage()
const stamp = Date.now()
await page.goto(BASE + '/hr?module=jobs', { waitUntil: 'networkidle' })
await page.waitForTimeout(1000)
await page.getByRole('button', { name: 'اضافة وظيفة', exact: true }).click()
await page.waitForTimeout(500)
await page.locator('[role=dialog] input').first().fill('دوره حياه ' + stamp)
await page.getByRole('button', { name: 'حفظ', exact: true }).click()
await page.waitForTimeout(1500)

await page.locator('input[placeholder="ابحث باسم او كود الوظيفة"]').fill('دوره حياه ' + stamp)
await page.waitForTimeout(1000)
await page.locator('tbody tr button[title="تعديل"]').first().click()
await page.waitForTimeout(600)
await page.locator('[role=dialog] input').first().fill('دوره حياه معدلة ' + stamp)
await page.getByRole('button', { name: 'حفظ', exact: true }).click()
await page.waitForTimeout(1500)

await page.locator('input[placeholder="ابحث باسم او كود الوظيفة"]').fill('معدلة ' + stamp)
await page.waitForTimeout(1000)
console.log('rows:', await page.locator('tbody tr').count())
await page.screenshot({ path: 'e2e-audit/apex/ours/before-delete-click.png' })
const delBtn = page.locator('tbody tr button[title="حذف"]').first()
console.log('delete btn visible:', await delBtn.isVisible().catch(e => 'ERR ' + e.message))
console.log('delete btn count:', await page.locator('tbody tr button[title="حذف"]').count())
await browser.close()
