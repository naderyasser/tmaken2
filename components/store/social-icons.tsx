export type SocialChannels = Record<string, string>

const SOCIALS: Array<{ key: string; label: string; Icon: ReturnType<typeof glyph> }> = [
  { key: 'whatsapp', label: 'واتساب', Icon: WhatsAppIcon },
  { key: 'snapchat', label: 'سناب شات', Icon: SnapchatIcon },
  { key: 'tiktok', label: 'تيك توك', Icon: TikTokIcon },
  { key: 'x', label: 'إكس (تويتر)', Icon: XIcon },
  { key: 'instagram', label: 'انستقرام', Icon: InstagramIcon },
]

export function SocialLinks({
  channels,
  className = '',
  iconClass = 'h-4.5 w-4.5',
  itemClass = 'flex h-10 w-10 items-center justify-center rounded-full bg-white/10 text-white hover:bg-white/20',
}: {
  channels: SocialChannels
  className?: string
  iconClass?: string
  itemClass?: string
}) {
  const items = SOCIALS.filter((s) => channels[s.key])
  if (!items.length) return null
  return (
    <div className={`flex items-center gap-2 ${className}`}>
      {items.map(({ key, label, Icon }) => (
        <a
          key={key}
          href={channels[key]}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={label}
          title={label}
          className={itemClass}
        >
          <Icon className={iconClass} style={{ width: '1.15rem', height: '1.15rem' }} />
        </a>
      ))}
    </div>
  )
}
